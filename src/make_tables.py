"""Aggregate scores.json files into results/summary.md (mean ± std over seeds) and summary.json."""

from __future__ import annotations

import json
import re
from collections import defaultdict

import numpy as np

from dico.common import RESULTS, TRACK_NAMES, TRACKS

METRICS = ["weighted_f1", "soft_cons", "hard_cons"]
SHORT = {"weighted_f1": "F1", "soft_cons": "Soft", "hard_cons": "Hard"}
SEED_RE = re.compile(r"^(?P<config>.+)_s(?P<seed>\d+)$")


def collect(split: str = "dev") -> dict:
    """config -> mode -> track -> metric -> list over seeds."""
    acc: dict = defaultdict(lambda: defaultdict(lambda: defaultdict(lambda: defaultdict(list))))
    for f in sorted((RESULTS / "runs").glob("*/scores.json")):
        m = SEED_RE.match(f.parent.name)
        if not m:
            continue
        scores = json.loads(f.read_text())
        for track, modes in scores.get(split, {}).items():
            for mode, s in modes.items():
                for k in METRICS:
                    acc[m["config"]][mode][track][k].append(s[k])
    return acc


def fmt(vals: list[float]) -> str:
    if len(vals) == 1:
        return f"{100 * vals[0]:.1f}"
    return f"{100 * np.mean(vals):.1f}±{100 * np.std(vals):.1f}"


def table(split: str) -> tuple[list[str], dict]:
    acc = collect(split)
    header = "| config | decoding | seeds | " + " | ".join(
        f"{TRACK_NAMES[t]} {SHORT[k]}" for t in TRACKS for k in METRICS
    ) + " | Avg F1 | Avg Soft | Avg Hard |"
    lines = [header, "|" + "---|" * (3 + 3 * len(TRACKS) + 3)]
    summary: dict = {}
    for config in sorted(acc):
        for mode in ["indep", "joint", "struct"]:
            if mode not in acc[config]:
                continue
            per = acc[config][mode]
            n = max(len(per[t]["weighted_f1"]) for t in per)
            cells, avg = [], defaultdict(list)
            for t in TRACKS:
                for k in METRICS:
                    v = per[t][k] if t in per else []
                    cells.append(fmt(v) if v else "–")
                    if v:
                        avg[k].append(np.mean(v))
            avg_cells = [f"{100 * np.mean(avg[k]):.1f}" if avg[k] else "–" for k in METRICS]
            lines.append(f"| {config} | {mode} | {n} | " + " | ".join(cells + avg_cells) + " |")
            summary.setdefault(config, {})[mode] = {
                t: {k: [float(np.mean(per[t][k])), float(np.std(per[t][k]))] for k in METRICS}
                for t in per
            }
    return lines, summary


def ensemble_lines(split: str) -> list[str]:
    lines = []
    for f in sorted((RESULTS / "ensembles").glob("*/scores.json")):
        scores = json.loads(f.read_text()).get(split, {})
        for mode in ["indep", "joint", "struct"]:
            cells = []
            for t in TRACKS:
                for k in METRICS:
                    cells.append(f"{100 * scores[t][mode][k]:.1f}" if t in scores else "–")
            lines.append(f"| {f.parent.name} (ens) | {mode} | – | " + " | ".join(cells) + " | | | |")
    return lines


def main() -> None:
    out = ["# Results summary (generated by src/make_tables.py)", ""]
    full = {}
    for split in ["dev", "val"]:
        lines, summary = table(split)
        full[split] = summary
        out += [f"## {split}", ""] + lines + (ensemble_lines(split) if split == "dev" else []) + [""]
    base = RESULTS / "baselines" / "scores_dev.json"
    if base.exists():
        b = json.loads(base.read_text())
        out += ["## dev baselines", "", "| baseline | " + " | ".join(f"{TRACK_NAMES[t]} {SHORT[k]}" for t in TRACKS for k in METRICS) + " |",
                "|" + "---|" * (1 + 3 * len(TRACKS))]
        for name in b["track1"]:
            out.append(f"| {name} | " + " | ".join(f"{100 * b[t][name][k]:.1f}" for t in TRACKS for k in METRICS) + " |")
    (RESULTS / "summary.md").write_text("\n".join(out) + "\n")
    (RESULTS / "summary.json").write_text(json.dumps(full, indent=2) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
